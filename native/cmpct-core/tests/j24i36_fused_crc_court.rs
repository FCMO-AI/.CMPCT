//! J24I36: compiled native verification of unchanged r24 frozen goldens
//! against single-bit, CRC-only physical-header mutations. Fixture sources
//! are independently authored; the detached referee authenticates bytes.
//! Ignored in normal suite: dedicated CI supplies physical files.
use cmpct_core::{Archive, CmpctError};
use std::env;
use std::path::{Path, PathBuf};

fn case_path(root: &Path, stem: &str, suffix: &str) -> PathBuf {
    root.join(format!("{stem}-{suffix}.cmpct"))
}

fn run_case(root: &Path, stem: &str) {
    let genuine =
        Archive::open(&case_path(root, stem, "original")).expect("immutable r24 golden must parse");
    assert_eq!(genuine.entries().len(), 1);
    assert_eq!(
        genuine
            .verify_complete()
            .expect("original direct must verify"),
        1,
        "{stem}"
    );
    let mutant = Archive::open(&case_path(root, stem, "crc-wrong"))
        .expect("one-bit CRC-only mutant remains index-parseable");
    match mutant.verify_complete() {
        Err(CmpctError::BlobHeader) => {
            println!("J24I36_CRC_REJECTED:{stem}:BlobHeader");
        }
        Err(error) => panic!("{stem}: unexpected refusal class: {error}"),
        Ok(count) => panic!("{stem}: CRC-only malformed header accepted ({count} payloads)"),
    }
}

#[test]
#[ignore = "requires fixed r24 source specimens provided by dedicated CI"]
fn j24i36_frozen_direct_codecs_reject_crc_only_mutation() {
    let root = PathBuf::from(env::var("J24I36_CASE_DIR").expect("CI must set J24I36_CASE_DIR"));
    for stem in ["raw", "zstd", "deflate"] {
        run_case(&root, stem);
    }
    println!("J24I36_FROZEN_DIRECT_SUCCESS:3");
}

#[test]
#[ignore = "requires exact symlink generated by installed Python Builder"]
fn j24i36_real_symlink_reject_crc_only_mutation() {
    let root = PathBuf::from(
        env::var("J24I36_SYMLINK_CASE_DIR").expect("CI must set J24I36_SYMLINK_CASE_DIR"),
    );
    let genuine = Archive::open(&root.join("original.cmpct")).expect("genuine symlink");
    assert_eq!(genuine.entries().len(), 1);
    assert_eq!(genuine.entries()[0].kind, 2);
    assert_eq!(genuine.verify_complete().expect("verify real symlink"), 1);
    let mutant = Archive::open(&root.join("crc-wrong.cmpct")).expect("CRC-only real symlink");
    assert!(
        matches!(mutant.verify_complete(), Err(CmpctError::BlobHeader)),
        "real symlink CRC-only mismatch must fail physical-header custody"
    );
    let payload_mutant =
        Archive::open(&root.join("physical-wrong.cmpct")).expect("physical payload mutant");
    assert!(
        matches!(
            payload_mutant.verify_complete(),
            Err(CmpctError::MemberHash)
        ),
        "physical payload mutation must retain SHA-based refusal"
    );
    println!("J24I36_REAL_SYMLINK_CRC_REJECTED");
}
