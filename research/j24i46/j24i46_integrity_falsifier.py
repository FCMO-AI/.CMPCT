#!/usr/bin/env python3
"""J24I46b: source-exact research falsifier for seek-only full-SHA equivalence.

No CMPCT import. Valid FLAC generated by j24i46_seek.py. Mutant intentionally
does NOT become an authenticated revision-24 archive.
"""
import argparse
import hashlib
import json
import subprocess
import wave
from pathlib import Path
import soundfile as sf


def digest(buf):
    return hashlib.sha256(buf).hexdigest()


def examine(path, start, expected, original_pcm_hash):
    ret = {}
    for mode in ("seek", "full"):
        try:
            with sf.SoundFile(str(path)) as flac:
                if mode == "seek":
                    flac.seek(start)
                    pcm = flac.buffer_read(1024, dtype="int16")
                    ret[mode] = {"accepted": len(pcm) == 4096,
                                 "requested_bytes_match": pcm == expected,
                                 "output_bytes": len(pcm)}
                else:
                    pcm = flac.buffer_read(flac.frames, dtype="int16")
                    ret[mode] = {"accepted": True, "full_pcm_sha256": digest(pcm),
                                 "full_pcm_match": digest(pcm) == original_pcm_hash,
                                 "output_bytes": len(pcm)}
        except Exception as exc:
            ret[mode] = {"accepted": False, "exception": str(exc)}
    return ret


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    d = args.out
    source = d / "stereo.flac"
    original_sha = digest(source.read_bytes())
    mutant = bytearray(source.read_bytes())
    byte_at = int(len(mutant) * 0.85)
    mutant[byte_at] ^= 0x04
    other = d / "stereo-mutant.flac"
    other.write_bytes(mutant)
    meta = json.loads((d / "generation.json").read_text())
    assert original_sha == meta["cases"]["stereo"]["flac_sha256"]
    with wave.open(str(d / "stereo.wav")) as wav:
        start = wav.getnframes() // 4
        wav.setpos(start)
        expected = wav.readframes(1024)
    original_pcm_hash = meta["cases"]["stereo"]["pcm_sha256"]
    clean = examine(source, start, expected, original_pcm_hash)
    corrupt = examine(other, start, expected, original_pcm_hash)
    reference_clean = subprocess.run(["flac", "--test", "--silent", str(source)], capture_output=True)
    reference_mutant = subprocess.run(["flac", "--test", "--silent", str(other)], capture_output=True)
    ret = {"schema": "cmpct-j24i46b-seek-integrity-falsifier-v1",
           "valid_flac_sha256": original_sha, "mutant_sha256": digest(mutant),
           "flipped_byte_offset": byte_at, "flipped_bit": 0x04,
           "original_bytes": len(mutant), "target_start_frame": start,
           "target_pcm_sha256": digest(expected),
           "clean": clean, "mutant": corrupt,
           "reference_flac_test_clean_exit": reference_clean.returncode,
           "reference_flac_test_mutant_exit": reference_mutant.returncode,
           "reference_flac_test_mutant_stderr": reference_mutant.stderr.decode(errors="replace")[:500]}
    (d / "integrity_falsifier.json").write_text(json.dumps(ret, indent=2, sort_keys=True) + "\n")
    print(json.dumps(ret, indent=2, sort_keys=True))
    assert reference_clean.returncode == 0 and reference_mutant.returncode != 0
    assert clean["seek"]["requested_bytes_match"] is True
    assert clean["full"]["full_pcm_match"] is True
    assert corrupt["seek"].get("requested_bytes_match") is True, "Oracle did not reproduce seek blindness"
    assert corrupt["full"].get("full_pcm_match") is not True, "Full decoder unexpectedly accepted same PCM"


if __name__ == "__main__":
    main()
