#!/usr/bin/env python3
"""J24I36 hosted symlink CRC court; one-bit mutation and detached r24 referee.

The first-party Builder fixture is generated by the unchanged J24I30 instrument.
This script does not import CMPCT. It reuses J24I30's separate wire parser so
the experiment tests a real signed r24 symlink, not an invented decoder.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "research" / "j24i30"))
from audit_symlink_wire import parse  # noqa: E402

HEADER = struct.Struct("<8sHHQQQ32s")
BLOB = struct.Struct("<4sBBHQQII32s")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--case-dir", type=Path, required=True)
    case_dir = ap.parse_args().case_dir
    source_path = case_dir / "original.cmpct"
    source = source_path.read_bytes()
    assert len(source) > HEADER.size + BLOB.size
    magic, version, flags, index_csize, _index_usize, span, _index_sha = HEADER.unpack_from(source)
    assert (magic, version, flags) == (b"CMPCT24\\0", 24, 0)
    record_start = HEADER.size + index_csize
    assert record_start + BLOB.size <= len(source)
    assert span >= BLOB.size
    bmagic, codec, bflags, reserved, usize, csize, meta_len, crc, digest = BLOB.unpack_from(
        source, record_start
    )
    assert (bmagic, codec, bflags, reserved, meta_len) == (b"CMA4", 0, 0, 0, 0)
    assert usize == csize == len(b"relative-symlink-target.txt")
    assert span == BLOB.size + csize
    crc_offset = record_start + 28
    original = parse(source_path)
    assert original["physical_record_valid"] is True
    assert bytes.fromhex(original["decoded_literal_hex"]) == b"relative-symlink-target.txt"
    assert original["decoded_bytes"] == usize
    assert original["decoded_sha256"] == digest.hex()
    assert original["logical_row_sha"] is None

    mutant = bytearray(source)
    mutant[crc_offset] ^= 1
    changed_path = case_dir / "crc-wrong.cmpct"
    changed_path.write_bytes(mutant)
    changed = parse(changed_path)
    differing = [i for i, (a, b) in enumerate(zip(source, mutant)) if a != b]
    assert len(source) == len(mutant) and differing == [crc_offset]
    assert (source[crc_offset] ^ mutant[crc_offset]) == 1
    assert original["physical_record_valid"] and not changed["physical_record_valid"]
    assert original["index_sha256"] == changed["index_sha256"]
    assert original["decoded_sha256"] == changed["decoded_sha256"]
    assert original["decoded_literal_hex"] == changed["decoded_literal_hex"]
    assert original["logical_row_sha"] == changed["logical_row_sha"]
    assert original["compressed_bytes"] == changed["compressed_bytes"]
    assert original["physical_sha256"] != changed["physical_sha256"]
    mutated_fields = BLOB.unpack_from(mutant, record_start)
    assert mutated_fields[:-2] == (bmagic, codec, bflags, reserved, usize, csize, meta_len)
    assert mutated_fields[-1] == digest
    assert mutated_fields[-2] == (crc ^ 1)

    result = {
        "schema": "j24i36-symlink-crc-only-detached-referee-v1",
        "result": "PASS",
        "source_sha256": sha(source),
        "mutated_sha256": sha(mutant),
        "source_decoded_sha256": original["decoded_sha256"],
        "mutation_position": crc_offset,
        "mutated_bit": 0,
        "original_crc32": crc,
        "mutated_crc32": crc ^ 1,
        "payload_and_index_unchanged": True,
        "physical_record_original_valid": True,
        "physical_record_mutant_valid": False,
        "scope": "real Builder symlink, r24 direct RAW only; not full product evidence",
    }
    (case_dir / "j24i36-symlink-independent-referee.json").write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\\n", encoding="utf-8"
    )
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
