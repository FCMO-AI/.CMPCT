#!/usr/bin/env python3
"""J24I50: fixed, Builder-independent r24 WAV/FLAC complete-verify public ABI court.

The archive is the committed independent conformance vector, not generated by the
candidate Builder. An 8-byte selective read is NOT a substitute for whole identity.
"""
from __future__ import annotations

import base64
import ctypes
import hashlib
import json
import os
import subprocess
import tempfile
from pathlib import Path

from cmpct.reader import CMPCT
from cmpct.codec import BHDR, K_FILE, K_HARDLINK
from cmpct.builder import Builder

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "native/cmpct-core/target/release/libcmpct_core.so"
CLI = ROOT / "native/cmpct-core/target/release/cmpct-native"
GOLDEN = ROOT / "tests/conformance/v24-wavflac.json"


def main() -> None:
    vector = json.loads(GOLDEN.read_text())["vector"]
    lib = ctypes.CDLL(str(LIB))
    lib.cmpct_open.argtypes = [ctypes.c_char_p, ctypes.POINTER(ctypes.c_void_p)]
    lib.cmpct_open.restype = ctypes.c_int32
    lib.cmpct_close.argtypes = [ctypes.c_void_p]
    lib.cmpct_verify_complete.argtypes = [
        ctypes.c_void_p,
        ctypes.POINTER(ctypes.c_size_t),
    ]
    lib.cmpct_verify_complete.restype = ctypes.c_int32
    lib.cmpct_entry_read_range.argtypes = [
        ctypes.c_void_p, ctypes.c_size_t, ctypes.c_uint64,
        ctypes.c_void_p, ctypes.c_size_t, ctypes.POINTER(ctypes.c_size_t),
    ]
    lib.cmpct_entry_read_range.restype = ctypes.c_int32

    def run_cli(path: Path, extra: tuple[str, ...] = ()) -> subprocess.CompletedProcess[bytes]:
        return subprocess.run(
            [str(CLI), "verify", str(path), *extra],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )

    def verify_abi(path: Path) -> tuple[int, int]:
        handle = ctypes.c_void_p()
        assert lib.cmpct_open(str(path).encode(), ctypes.byref(handle)) == 0
        assert handle.value is not None
        try:
            count = ctypes.c_size_t(999)
            status = lib.cmpct_verify_complete(handle, ctypes.byref(count))
            return status, count.value
        finally:
            lib.cmpct_close(handle)

    with tempfile.TemporaryDirectory(prefix="cmpct-j24i50-") as td:
        root = Path(td)
        original = root / "fixed-wavflac.cmpct"
        raw = base64.b64decode(vector["archive_base64"])
        assert len(raw) == vector["archive_bytes"]
        assert hashlib.sha256(raw).hexdigest() == vector["archive_sha256"]
        original.write_bytes(raw)

        with CMPCT(original) as python_archive:
            assert python_archive.verify() == 1
            row = python_archive.by[vector["name"]]
            blob_index = row[6][1]
            blob_pos = python_archive.record_base + python_archive.blobs[blob_index][0]

        assert verify_abi(original) == (0, 1)
        clean_cli = run_cli(original)
        assert clean_cli.returncode == 0, clean_cli.stderr
        assert json.loads(clean_cli.stdout) == {"revision": 24, "verified": 1}

        # J24I50d: an external C caller holds the original Archive handle while
        # the *pathname* is rebound to different (index-admissible) archive bytes.
        # Only the old handle may certify the original inode. New pathname opens
        # and the CLI must reject the mutated physical SHA; no Python delegation.
        py_owned = CMPCT(original)
        owned = ctypes.c_void_p()
        assert lib.cmpct_open(str(original).encode(), ctypes.byref(owned)) == 0
        assert owned.value is not None
        retained = root / "retained-original-wavflac.cmpct"
        assert not retained.exists()
        original.rename(retained)
        replacement = bytearray(raw)
        replacement[blob_pos + 32] ^= 1
        original.write_bytes(replacement)
        assert hashlib.sha256(retained.read_bytes()).hexdigest() == vector["archive_sha256"]
        assert hashlib.sha256(original.read_bytes()).hexdigest() != vector["archive_sha256"]
        assert retained.stat().st_ino != original.stat().st_ino
        try:
            # A Python Reader already open on the original source must not be
            # accidentally conflated with a late pathname-opened native handle.
            assert py_owned.verify() == 1
            old_count = ctypes.c_size_t(999)
            assert lib.cmpct_verify_complete(owned, ctypes.byref(old_count)) == 0
            assert old_count.value == 1
            replaced_status, replaced_count = verify_abi(original)
            assert replaced_status != 0 and replaced_count == 0
            bad_rebound_cli = run_cli(original)
            assert bad_rebound_cli.returncode != 0 and bad_rebound_cli.stdout == b""
            assert verify_abi(retained) == (0, 1)
            good_retained_cli = run_cli(retained)
            assert good_retained_cli.returncode == 0, good_retained_cli.stderr
            assert json.loads(good_retained_cli.stdout) == {"revision": 24, "verified": 1}
            # J24I50f: a *valid but different* archive is a sharper control
            # than a corrupted replacement. Both native verifications can succeed
            # while claiming different source objects when opened by pathname.
            fixed_direct = json.loads(
                (ROOT / "tests/conformance/v24-direct-codecs.json").read_text()
            )
            foreign = next(v for v in fixed_direct["vectors"] if v["codec"] == 0)
            assert foreign["name"] != vector["name"]
            foreign_bytes = base64.b64decode(foreign["archive_base64"])
            assert hashlib.sha256(foreign_bytes).hexdigest() == foreign["archive_sha256"]
            assert foreign["archive_sha256"] != vector["archive_sha256"]
            original.write_bytes(foreign_bytes)
            assert hashlib.sha256(retained.read_bytes()).hexdigest() == vector["archive_sha256"]
            assert py_owned.verify() == 1
            assert vector["name"] in py_owned.by and foreign["name"] not in py_owned.by
            again = ctypes.c_size_t(999)
            assert lib.cmpct_verify_complete(owned, ctypes.byref(again)) == 0
            assert again.value == 1
            assert verify_abi(original) == (0, 1)
            with CMPCT(original) as new_python:
                assert new_python.verify() == 1
                assert foreign["name"] in new_python.by
                assert vector["name"] not in new_python.by
            good_foreign_cli = run_cli(original)
            assert good_foreign_cli.returncode == 0, good_foreign_cli.stderr
            assert json.loads(good_foreign_cli.stdout) == {"revision": 24, "verified": 1}
        finally:
            lib.cmpct_close(owned)
            py_owned.close()
            original.unlink()
            retained.rename(original)
        assert hashlib.sha256(original.read_bytes()).hexdigest() == vector["archive_sha256"]

        # Valid handle, null count pointer: report error rather than crossing ABI
        # with an invalid writable pointer. Null archive must also clear a valid count.
        count = ctypes.c_size_t(999)
        assert lib.cmpct_verify_complete(None, ctypes.byref(count)) == -1
        assert count.value == 0
        handle = ctypes.c_void_p()
        assert lib.cmpct_open(str(original).encode(), ctypes.byref(handle)) == 0
        try:
            assert lib.cmpct_verify_complete(handle, None) == -1
        finally:
            lib.cmpct_close(handle)

        # A one-bit physical CMA4 content commitment mutation leaves the
        # independent FLAC frames valid but MUST fail whole-member verification.
        altered = bytearray(raw)
        altered[blob_pos + 32] ^= 1
        damaged = root / "corrupt-physical-hash.cmpct"
        damaged.write_bytes(altered)
        assert verify_abi(damaged) == (-3, 0)
        bad_cli = run_cli(damaged)
        assert bad_cli.returncode != 0
        assert bad_cli.stdout == b""
        try:
            with CMPCT(damaged) as py_bad:
                py_bad.verify()
        except (OSError, IOError, ValueError):
            pass
        else:
            raise AssertionError("Python reference unexpectedly accepted corrupt physical SHA")

        # No speculative command success when options change the contract.
        extra_cli = run_cli(original, ("unexpected",))
        assert extra_cli.returncode != 0
        assert extra_cli.stdout == b""

        # A RAW partial read is deliberately local: untouched bytes can be
        # served without certifying the entire member. Full verify must catch
        # late physical corruption despite a successful early range result.
        direct = json.loads(
            (ROOT / "tests/conformance/v24-direct-codecs.json").read_text()
        )
        raw_vector = next(v for v in direct["vectors"] if v["codec"] == 0)
        raw_bytes = base64.b64decode(raw_vector["archive_base64"])
        assert hashlib.sha256(raw_bytes).hexdigest() == raw_vector["archive_sha256"]
        raw_path = root / "fixed-raw.cmpct"
        raw_path.write_bytes(raw_bytes)
        assert verify_abi(raw_path) == (0, 1)
        with CMPCT(raw_path) as ar:
            row = ar.by[raw_vector["name"]]
            off, usize, csize, codec, mlen = ar.blobs[row[6][1]]
            assert codec == 0 and csize == usize and usize == 64
            payload_pos = ar.record_base + off + BHDR.size + mlen
        raw_mutation = bytearray(raw_bytes)
        raw_mutation[payload_pos + csize - 1] ^= 1
        raw_bad_path = root / "fixed-raw-corrupt-late.cmpct"
        raw_bad_path.write_bytes(raw_mutation)
        handle = ctypes.c_void_p()
        assert lib.cmpct_open(str(raw_bad_path).encode(), ctypes.byref(handle)) == 0
        try:
            early = ctypes.create_string_buffer(1)
            got = ctypes.c_size_t()
            assert lib.cmpct_entry_read_range(
                handle, 0, 0, early, 1, ctypes.byref(got)
            ) == 0
            assert got.value == 1
            # The selected byte is unmodified even though the archive is not intact.
            assert early.raw == raw_bytes[payload_pos:payload_pos + 1]
            count = ctypes.c_size_t(777)
            assert lib.cmpct_verify_complete(handle, ctypes.byref(count)) != 0
            assert count.value == 0
        finally:
            lib.cmpct_close(handle)
        raw_bad_cli = run_cli(raw_bad_path)
        assert raw_bad_cli.returncode != 0 and raw_bad_cli.stdout == b""

        # J24I50c prospective control: native "verified" counts authenticated
        # payload owners, whereas Python verify counts logical hardlink aliases too.
        # This is Builder-derived regression evidence, NOT a frozen format oracle.
        hardlink_root = root / "source-hardlink"
        hardlink_root.mkdir()
        owner = hardlink_root / "a-owner.bin"
        owner.write_bytes(b"hardlink-content-identity\x00" * 1024)
        os.link(owner, hardlink_root / "z-alias.bin")
        hardlink_archive = root / "real-hardlink.cmpct"
        Builder(hardlink_root, workers=1).build(hardlink_archive)
        with CMPCT(hardlink_archive) as py_links:
            kinds = sorted(row[1] for row in py_links.files)
            assert kinds == [K_FILE, K_HARDLINK], kinds
            python_hardlink_count = py_links.verify()
            assert python_hardlink_count == 2
        assert verify_abi(hardlink_archive) == (0, 1)
        links_cli = run_cli(hardlink_archive)
        assert links_cli.returncode == 0, links_cli.stderr
        assert json.loads(links_cli.stdout) == {"revision": 24, "verified": 1}

        # J24I62: latest signed generations must never inherit a false
        # native full-verify SUCCESS for the old primary member set.
        # J24I51 already proved this same-inode mismatch on authentic public
        # Writer operations; this test is the prospective repair gate.
        from cmpct.transactions import append_update, append_delete, append_rename
        journal = root / "same-inode-signed-generations.cmpct"
        journal.write_bytes(raw)
        original_inode = journal.stat().st_ino
        source = root / "new-physical-member.bin"
        source.write_bytes(b"new signed generation content\\0" * 111)
        append_update(journal, "new-member.bin", source)
        with CMPCT(journal) as current:
            assert current.verify() == 2
            assert "new-member.bin" in current.by and vector["name"] in current.by
        status, count = verify_abi(journal)
        assert status == -7 and count == 0, ("signed put must be unsupported", status, count)
        rejected_put = run_cli(journal)
        assert rejected_put.returncode != 0 and rejected_put.stdout == b""
        append_delete(journal, vector["name"])
        assert journal.stat().st_ino == original_inode
        assert journal.read_bytes().startswith(raw)
        with CMPCT(journal) as current:
            assert current.verify() == 1
            assert "new-member.bin" in current.by and vector["name"] not in current.by
        status, count = verify_abi(journal)
        assert status == -7 and count == 0, ("signed delete must be unsupported", status, count)
        rejected_delete = run_cli(journal)
        assert rejected_delete.returncode != 0 and rejected_delete.stdout == b""

        # Checkpoint at generation 64 has kind=0 but prev!=0. A test that
        # only rejects kind=1 deltas would incorrectly certify this stale root.
        checkpoint = root / "signed-checkpoint64.cmpct"
        checkpoint.write_bytes(raw)
        current_name = vector["name"]
        alternative_name = "rotated-wav-member.wav"
        for _ in range(64):
            next_name = alternative_name if current_name == vector["name"] else vector["name"]
            append_rename(checkpoint, current_name, next_name)
            current_name = next_name
        with CMPCT(checkpoint) as current:
            assert current.verify() == 1
            assert current_name in current.by
        status, count = verify_abi(checkpoint)
        assert status == -7 and count == 0, ("signed checkpoint must be unsupported", status, count)
        rejected_checkpoint = run_cli(checkpoint)
        assert rejected_checkpoint.returncode != 0 and rejected_checkpoint.stdout == b""

        print(json.dumps({
            "schema": "cmpct-j24i50-native-public-verify-v1",
            "fixed_vector_sha256": vector["archive_sha256"],
            "fixed_vector": vector["name"],
            "normal_abi": "success-1",
            "normal_cli": "success-1",
            "opened_handle_rebind": "original-inode-pass-fresh-replacement-rejected",
            "python_native_path_reopen": "held-python-original-pass-fresh-native-rejected",
            "valid_foreign_path_reopen": "both-pass-different-source-and-member",
            "corrupt_sha_abi": "fail-closed-count-0",
            "corrupt_sha_cli": "fail-closed-empty-stdout",
            "python_reference_corruption": "rejected",
            "null_pointer_tests": 2,
            "raw_late_corrupt_early_range": "accepted-local",
            "raw_late_corrupt_complete_abi": "rejected-count-0",
            "raw_late_corrupt_complete_cli": "rejected-empty-stdout",
            "hardlink_python_logical_count": 2,
            "hardlink_native_payload_owner_count": 1,
            "latest_signed_put_delete_native": "typed-unsupported-count-0",
            "latest_signed_checkpoint64_native": "typed-unsupported-count-0",
        }, sort_keys=True))


if __name__ == "__main__":
    main()
