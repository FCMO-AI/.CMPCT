#!/usr/bin/env python3
"""J24G34 same-*physical-source*, same-host A/B/B/A compaction economics.

Scientific extension of the prospective J24G34 composition contract; not a
release performance test. Historical #737 original negative and #620 source
tests remain immutable. Uses the physical r24 source generated by the J24G34
product court, not separately randomized benchmark trees.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

SIZE = 128 << 20
NAME = "source-134217728-alias1.cmpct"


def digest(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    root = Path(os.environ["J24G34_ARTIFACT_DIR"]).resolve()
    root.mkdir(exist_ok=True, parents=True)
    source = root / NAME
    assert source.is_file() and source.stat().st_size < 16 * 1024 * 1024
    original_sha = digest(source)
    runners = {
        # NEVER Path.resolve() a venv python symlink: that dereferences to the
        # global base interpreter and silently erases A/B source provenance.
        "A_baseline": Path(os.environ["J24G34_BASE_PYTHON"]).absolute(),
        "B_candidate": Path(os.environ["J24G34_CAND_PYTHON"]).absolute(),
    }
    src_script = Path(__file__).with_name("j24g34_sparse_alias_product_court.py")
    assert src_script.is_file()
    all_runs = []
    for index, label in enumerate(("A_baseline", "B_candidate", "B_candidate", "A_baseline")):
        python = runners[label]
        assert python.is_file(), python
        assert (python.parent.parent / "pyvenv.cfg").is_file(), ("lost venv entry point", python)
        output = root / f"samewire-{index}-{label}.cmpct"
        receipt = root / f"samewire-{index}-{label}.json"
        proc = subprocess.run(
            [str(python), str(src_script), "--child", str(SIZE), "1",
             str(source), str(output), str(receipt)],
            cwd=os.environ.get("RUNNER_TEMP", "/tmp"),
            capture_output=True, text=True, timeout=300,
            env={**os.environ, "CMPCT_ENCODE_WORKERS": "1",
                 "J24G34_EXPECTED_READER_BLOB": (
                     "b2b7774c13a5c8235ff89786d171b7ea3ff20710" if label=="A_baseline"
                     else "f2bf7e5ca79f35706bc7d09a496eba9ef151fc1f")},
        )
        (root / f"samewire-{index}-{label}.stdout").write_text(proc.stdout)
        (root / f"samewire-{index}-{label}.stderr").write_text(proc.stderr)
        if proc.returncode:
            raise AssertionError(f"{label} rc={proc.returncode}: {proc.stderr[-2000:]}")
        item = json.loads(receipt.read_text())
        assert item["genuine_hardlink_alias"]
        assert item["rows_metadata_and_sha_equal"] and item["source_unchanged"]
        assert item["source_sha256"] == original_sha
        assert item["installed_reader_git_blob"] == (
            "b2b7774c13a5c8235ff89786d171b7ea3ff20710" if label=="A_baseline"
            else "f2bf7e5ca79f35706bc7d09a496eba9ef151fc1f"), item
        assert digest(output) == item["output_sha256"]
        assert item["output_bytes"] == output.stat().st_size
        item["runner"] = label
        item["trial"] = index
        all_runs.append(item)

    assert digest(source) == original_sha
    base = [x for x in all_runs if x["runner"] == "A_baseline"]
    candidate = [x for x in all_runs if x["runner"] == "B_candidate"]
    assert len(base) == len(candidate) == 2
    outputs = {x["output_sha256"] for x in all_runs}
    same_output = len(outputs) == 1
    base_min = min(x["peak_rss_kib_compaction"] for x in base)
    cand_max = max(x["peak_rss_kib_compaction"] for x in candidate)
    conservative_delta = base_min - cand_max
    report = {
        "schema": "cmpct-j24g34-same-wire-verified-reader-abba-v1",
        "source_sha256": original_sha,
        "same_source_all_trials": True,
        "same_semantics_and_output_sha": same_output,
        "baseline_reader_blob": "b2b7774c13a5c8235ff89786d171b7ea3ff20710",
        "candidate_reader_blob": "f2bf7e5ca79f35706bc7d09a496eba9ef151fc1f",
        "source_parent": "82e90eca58ed0580df191378947004e4061d53c3",
        "baseline_min_rss_kib": base_min,
        "candidate_max_rss_kib": cand_max,
        "conservative_saving_kib": conservative_delta,
        "raw_trials": all_runs,
        "decision": ("COMPOSITION_SAME_WIRE_MEMORY_GAIN_REPLICATED"
                     if same_output and cand_max < 64 * 1024
                     and conservative_delta >= 64 * 1024
                     else "SAME_WIRE_COMPOSITION_NOT_CONFIRMED"),
        "product_candidate_only": True,
        "release_credit": 0,
    }
    (root / "samewire-abba-report.json").write_text(json.dumps(report,sort_keys=True,indent=2)+"\n")
    print(json.dumps(report,sort_keys=True,indent=2))
    assert report["decision"] == "COMPOSITION_SAME_WIRE_MEMORY_GAIN_REPLICATED", report


if __name__ == "__main__":
    main()
